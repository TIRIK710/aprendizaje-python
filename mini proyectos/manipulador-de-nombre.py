nombre = "Miguel Medina"

print("1.", nombre) # muestra el nombre sin alterar

print("2.", nombre.upper()) # muestra el nombre todo en mayusculas

print("3.", nombre.lower()) # muestra el nombre todo en minusculas

print("4.", "x" in nombre) # muestra si la x esta o no

print("5.", "i" in nombre) # muestra si la i esta o no

print("6.", nombre.find("l")) # muestra la posicion del caracter l

print("7.", nombre.find("Me")) # muestra la posicion de la silaba me

print("8.", nombre.find("lo")) # muestra si la silaba lo esta o no (-1 = no esta)

# los numeros al principio del print son para identificar con mas facilidad
# que resultados en la terminal corresponden a que funcion